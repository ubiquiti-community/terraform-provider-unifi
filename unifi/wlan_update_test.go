// newWLANHarness serves document as the WLAN. Like the controller, the fake
// generates a passphrase when a create request has none.
func newWLANHarness(t *testing.T, document string) *updateHarness {
	t.Helper()
	h := newUpdateHarness(t, "unifi_wlan", "wlanconf", wlanTestID, document,
		func(c *Client) harnessResource { return &wlanFrameworkResource{client: c} })
	h.fake.onPost = func(body map[string]any) {
		if _, ok := body["x_passphrase"]; !ok {
			body["x_passphrase"] = "controller-generated"
		}
	}
	return h
}

func newImportedWLANHarness(t *testing.T, document string) *updateHarness {
	t.Helper()
	h := newWLANHarness(t, document)
	h.importAndRead()
	return h
}

// newAdoptedWLANHarness imports the WLAN and applies wlanBaseConfig once. The
// first apply after an import sends the configured passphrase, because a
// refresh keeps a null passphrase null (#392).
func newAdoptedWLANHarness(t *testing.T) *updateHarness {
	t.Helper()
	h := newImportedWLANHarness(t, wlanTestDocument)
	h.apply(h.config(wlanBaseConfig()))
	return h
}

// wlanBaseConfig matches wlanTestDocument. network_id and ap_group.ids are
// Optional-only, and mac_filter differs from its nested defaults, so leaving
// any of them out plans a change.
func wlanBaseConfig() map[string]attr.Value {
	return map[string]attr.Value{
		"name":          types.StringValue("office"),
		"user_group_id": types.StringValue("6650aa00000000000000b001"),
		"security":      types.StringValue("wpapsk"),
		"passphrase":    types.StringValue("correct-horse-battery"),
		"network_id":    types.StringValue("6650aa00000000000000c001"),
		"mac_filter":    wlanMacFilter("02:00:00:00:00:01", "02:00:00:00:00:02"),
		"ap_group": types.ObjectValueMust(wlanApGroupAttrTypes(), map[string]attr.Value{
			"ids": types.SetValueMust(types.StringType, []attr.Value{
				types.StringValue("6650aa00000000000000d001"),
			}),
			"mode": types.StringNull(),
		}),
	}
}

func wlanMacFilter(macs ...string) attr.Value {
	list := types.SetNull(types.StringType)
	if len(macs) > 0 {
		vals := make([]attr.Value, len(macs))
		for i, mac := range macs {
			vals[i] = types.StringValue(mac)
		}
		list = types.SetValueMust(types.StringType, vals)
	}
	return types.ObjectValueMust(
		map[string]attr.Type{
			"enabled": types.BoolType,
			"list":    types.SetType{ElemType: types.StringType},
			"policy":  types.StringType,
		},
		map[string]attr.Value{
			"enabled": types.BoolValue(true),
			"list":    list,
			"policy":  types.StringValue("allow"),
		},
	)
}

func Test_wlanFrameworkResource_Update(t *testing.T) {
	t.Run("import with an unmanaged passphrase plans nothing", func(t *testing.T) {
		h := newImportedWLANHarness(t, wlanTestDocument)
		cfg := wlanBaseConfig()
		delete(cfg, "passphrase")
		h.assertEqual("plan after import", h.state.Raw, h.plan(h.config(cfg)))
	})

	t.Run("import, first apply and an empty second plan", func(t *testing.T) {
		h := newImportedWLANHarness(t, wlanTestDocument)
		assertBodies(t, h.apply(h.config(wlanBaseConfig())),
			`{"x_passphrase":"correct-horse-battery"}`)
	})

	t.Run("an unrelated change sends exactly that key", func(t *testing.T) {
		h := newAdoptedWLANHarness(t)
		cfg := wlanBaseConfig()
		cfg["hide_ssid"] = types.BoolValue(true)
		assertBodies(t, h.apply(h.config(cfg)), `{"hide_ssid":true}`)
		for key, want := range map[string]any{
			"minrate_na_enabled": false,
			"x_iapp_key":         "00112233445566778899aabbccddeeff",
			"setting_preference": "manual",
			"short_id":           json.Number("3"),
		} {
			if got := h.fake.stored(key); got != want {
				t.Errorf("stored %s = %v, want %v", key, got, want)
			}
		}
		if got := h.fake.stored("name_combine_enabled"); got != nil {
			t.Errorf("stored name_combine_enabled = %v, want absent", got)
		}
	})

	t.Run("nothing to change sends no PUT", func(t *testing.T) {
		h := newAdoptedWLANHarness(t)
		cfg := wlanBaseConfig()
		cfg["timeouts"] = types.ObjectValueMust(
			timeoutsNullValue().AttributeTypes(h.ctx),
			map[string]attr.Value{
				"create": types.StringNull(),
				"delete": types.StringNull(),
				"read":   types.StringNull(),
				"update": types.StringValue("30m"),
			},
		)
		assertBodies(t, h.apply(h.config(cfg)))
	})

	t.Run("unknown planned values take the prior value, never a zero", func(t *testing.T) {
		h := newAdoptedWLANHarness(t)
		cfg := wlanBaseConfig()
		roaming := func(rssi int64) attr.Value {
			return types.ObjectValueMust(wlanRoamingAssistantAttrTypes(), map[string]attr.Value{
				"enabled": types.BoolNull(),
				"rssi":    types.Int64Value(rssi),
			})
		}
		cfg["roaming_assistant_na"] = roaming(-75)
		cfg["roaming_assistant_6e"] = roaming(-80)
		config := h.config(cfg)

		var enabled types.Bool
		planned := tfsdk.Plan{Schema: h.schema, Raw: h.plan(config)}
		planned.GetAttribute(h.ctx,
			path.Root("roaming_assistant_6e").AtName("enabled"), &enabled)
		if !enabled.IsUnknown() {
			t.Fatalf("roaming_assistant_6e.enabled planned %v, want unknown", enabled)
		}

		assertBodies(t, h.apply(config),
			`{"roaming_assistant_6e_enabled":true,"roaming_assistant_6e_rssi":-80}`)
	})

	t.Run("an unknown set element fails before any request", func(t *testing.T) {
		h := newAdoptedWLANHarness(t)
		cfg := wlanBaseConfig()
		cfg["hide_ssid"] = types.BoolValue(true)
		config := h.config(cfg)
		planned := tfsdk.Plan{Schema: h.schema, Raw: h.plan(config)}
		planned.SetAttribute(h.ctx, path.Root("ap_group").AtName("ids"),
			types.SetValueMust(types.StringType, []attr.Value{types.StringUnknown()}))
		sent := h.fake.putCount()
		detail := diagDetails(h.update(planned.Raw, config))
		for _, want := range []string{
			"no request was sent",
			`AttributeName("ap_group").AttributeName("ids").ElementKeyValue`,
			"unknown value has no prior value",
		} {
			if !strings.Contains(detail, want) {
				t.Errorf("diagnostic %q lacks %q", detail, want)
			}
		}
		if n := h.fake.putCount() - sent; n != 0 {
			t.Errorf("%d PUTs sent, want none", n)
		}
	})

	t.Run("an explicit false is sent", func(t *testing.T) {
		h := newAdoptedWLANHarness(t)
		cfg := wlanBaseConfig()
		cfg["iapp_enabled"] = types.BoolValue(false)
		assertBodies(t, h.apply(h.config(cfg)), `{"iapp_enabled":false}`)
	})

	t.Run("a removed list is cleared with its group", func(t *testing.T) {
		h := newAdoptedWLANHarness(t)
		cfg := wlanBaseConfig()
		cfg["mac_filter"] = wlanMacFilter()
		assertBodies(t, h.apply(h.config(cfg)),
			`{"mac_filter_enabled":true,"mac_filter_list":[],"mac_filter_policy":"allow"}`)
	})

	t.Run("a rate change sends its minrate flag", func(t *testing.T) {
		h := newAdoptedWLANHarness(t)
		cfg := wlanBaseConfig()
		cfg["minimum_data_rate_5g_kbps"] = types.Int64Value(12000)
		assertBodies(t, h.apply(h.config(cfg)),
			`{"minrate_na_data_rate_kbps":12000,"minrate_na_enabled":true}`)
	})

	t.Run("a changed passphrase is sent", func(t *testing.T) {
		h := newAdoptedWLANHarness(t)
		cfg := wlanBaseConfig()
		cfg["passphrase"] = types.StringValue("new-passphrase-1")
		assertBodies(t, h.apply(h.config(cfg)), `{"x_passphrase":"new-passphrase-1"}`)
	})

	t.Run("passphrase_wo is sent only when its version changes", func(t *testing.T) {
		h := newImportedWLANHarness(t, wlanTestDocument)
		cfg := wlanBaseConfig()
		delete(cfg, "passphrase")
		cfg["passphrase_wo"] = types.StringValue("rotated-secret-1")
		cfg["passphrase_wo_version"] = types.Int64Value(1)
		assertBodies(t, h.apply(h.config(cfg)), `{"x_passphrase":"rotated-secret-1"}`)

		cfg["passphrase_wo"] = types.StringValue("rotated-secret-2")
		cfg["hide_ssid"] = types.BoolValue(true)
		assertBodies(t, h.apply(h.config(cfg)), `{"hide_ssid":true}`)

		cfg["passphrase_wo_version"] = types.Int64Value(2)
		assertBodies(t, h.apply(h.config(cfg)), `{"x_passphrase":"rotated-secret-2"}`)

		if got := h.fake.stored("x_passphrase"); got != "rotated-secret-2" {
			t.Errorf("stored x_passphrase = %v", got)
		}
		var passphrase types.String
		h.state.GetAttribute(h.ctx, path.Root("passphrase"), &passphrase)
		if !passphrase.IsNull() {
			t.Errorf("state passphrase = %v, want null although the controller echoes it",
				passphrase)
		}
	})

	t.Run("removing vlan fails before any request", func(t *testing.T) {
		document := strings.Replace(wlanTestDocument, `"hide_ssid": false,`,
			`"hide_ssid": false, "vlan_enabled": true, "vlan": 42,`, 1)
		cfg := wlanBaseConfig()
		cfg["vlan_enabled"] = types.BoolValue(true)
		cfg["vlan"] = types.Int64Value(42)
		h := newImportedWLANHarness(t, document)
		h.apply(h.config(cfg))

		delete(cfg, "vlan")
		config := h.config(cfg)
		sent := h.fake.putCount()
		diags := h.update(h.plan(config), config)
		if !diags.HasError() || !strings.Contains(diagDetails(diags), `"vlan"`) {
			t.Fatalf("diagnostics = %v, want an error naming vlan", diags)
		}
		if n := h.fake.putCount() - sent; n != 0 {
			t.Errorf("%d PUTs sent, want none", n)
		}
	})

	t.Run("a controller error names the sent keys, not their values", func(t *testing.T) {
		h := newAdoptedWLANHarness(t)
		h.fake.reject = func(map[string]any) string { return "api.err.InvalidPayload" }
		cfg := wlanBaseConfig()
		cfg["passphrase"] = types.StringValue("new-passphrase-1")
		config := h.config(cfg)
		diags := h.update(h.plan(config), config)
		detail := diagDetails(diags)
		for _, want := range []string{
			"api.err.InvalidPayload",
			"The request set x_passphrase.",
			"merged",
		} {
			if !strings.Contains(detail, want) {
				t.Errorf("diagnostic %q lacks %q", detail, want)
			}
		}
		if strings.Contains(detail, "new-passphrase-1") {
			t.Errorf("diagnostic leaks the passphrase: %q", detail)
		}
	})
}

// The controller generates a passphrase when the create request has none and
// echoes it on every read. State must keep the planned null (#583).
func Test_wlanFrameworkResource_Create(t *testing.T) {
	h := newWLANHarness(t, `{}`)
	cfg := wlanBaseConfig()
	delete(cfg, "passphrase")
	config := h.config(cfg)
	planned := h.plan(config)

	resp := &fwresource.CreateResponse{
		State:    tfsdk.State{Schema: h.schema, Raw: planned.Copy()},
		Identity: &tfsdk.ResourceIdentity{Schema: h.identity.Schema, Raw: h.identity.Raw.Copy()},
	}
	h.r.Create(h.ctx, fwresource.CreateRequest{
		Config: tfsdk.Config{Schema: h.schema, Raw: config},
		Plan:   tfsdk.Plan{Schema: h.schema, Raw: planned},
	}, resp)
	if resp.Diagnostics.HasError() {
		t.Fatalf("Create: %v", resp.Diagnostics)
	}
	resolved, err := util.ResolveUnknowns(planned, resp.State.Raw)
	if err != nil {
		t.Fatalf("resolving the plan from the new state: %v", err)
	}
	h.assertEqual("state after Create differs from the plan", resolved, resp.State.Raw)
	if got := h.fake.stored("x_passphrase"); got != "controller-generated" {
		t.Errorf("stored x_passphrase = %v", got)
	}
}

// Every Clear and group key must be a key of the go-unifi WLAN encoding, or
// Diff silently ignores it.
func TestWLANDiffOptionsKeysExist(t *testing.T) {
	keys := map[string]bool{}
	typ := reflect.TypeFor[unifi.WLAN]()
	for i := range typ.NumField() {
		name, _, _ := strings.Cut(typ.Field(i).Tag.Get("json"), ",")
		keys[name] = true
	}
	check := func(k string) {
		if !keys[k] {
			t.Errorf("%q is not a key of unifi.WLAN", k)
		}
	}
	for _, k := range wlanDiffOptions.Clear {
		check(k)
	}
	for _, group := range wlanDiffOptions.Groups {
		for _, k := range group {
			check(k)
		}
	}
}

// TestAccWLANFramework_sparseUpdate creates a WLAN, changes one attribute and
// imports it, and expects an empty plan after each apply.
func TestAccWLANFramework_sparseUpdate(t *testing.T) {
	if os.Getenv("TF_ACC") == "" {
		t.Skip("TF_ACC not set, skipping acceptance test")
	}
	userGroupID := testAccWLANDefaultUserGroupID(t)
	emptyPlan := resource.ConfigPlanChecks{
		PostApplyPostRefresh: []plancheck.PlanCheck{plancheck.ExpectEmptyPlan()},
	}

	resource.Test(t, resource.TestCase{
		PreCheck:                 func() { preCheck(t) },
		ProtoV6ProviderFactories: testAccProtoV6ProviderFactories,
		Steps: []resource.TestStep{
			{
				Config:           testAccWLANFrameworkConfig_sparseUpdate(userGroupID, false),
				ConfigPlanChecks: emptyPlan,
			},
			{
				Config:           testAccWLANFrameworkConfig_sparseUpdate(userGroupID, true),
				ConfigPlanChecks: emptyPlan,
				Check: resource.TestCheckResourceAttr(
					"unifi_wlan.test_sparse", "hide_ssid", "true"),
			},
			{
				ResourceName:      "unifi_wlan.test_sparse",
				ImportState:       true,
				ImportStateVerify: true,
			},
		},
	})
}

